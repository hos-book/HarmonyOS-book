"""Generate typed, pinned Kokoro assets and speaker identities for ArkTS."""
import argparse
import json
import re
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parent.parent
SPEC_PATH = ROOT / 'scripts/offline-tts-assets.json'
OUTPUT_PATH = ROOT / 'entry/src/main/ets/model/OfflineTtsAssets.ets'


def generate() -> str:
    spec = json.loads(SPEC_PATH.read_text(encoding='utf-8'))
    assets = spec['files']
    paths: set[str] = set()
    for item in assets:
        path = item['path']
        if (not path or path in paths or '\\' in path or ':' in path
                or PurePosixPath(path).is_absolute() or '..' in path.split('/')
                or item['bytes'] <= 0 or re.fullmatch(r'[0-9a-f]{64}', item['sha256']) is None):
            raise ValueError(f'Invalid pinned asset: {path}')
        paths.add(path)
    speakers = spec['speakers']
    if len(speakers) != 103 or [item['id'] for item in speakers] != list(range(103)):
        raise ValueError('Kokoro v1.1-zh requires the pinned 103-speaker order')
    output = '''// Generated by scripts/generate-offline-tts-assets.py; do not edit checksums manually.
// Source revision and SHA256 provenance: scripts/offline-tts-assets.json.
export class OfflineTtsPinnedAsset {
  name: string;
  bytes: number;
  sha256: string;
  constructor(name: string, bytes: number, sha256: string) {
    this.name = name;
    this.bytes = bytes;
    this.sha256 = sha256;
  }
}

export class OfflineTtsPinnedSpeaker {
  id: number;
  name: string;
  language: string;
  gender: string;
  constructor(id: number, name: string, language: string, gender: string) {
    this.id = id;
    this.name = name;
    this.language = language;
    this.gender = gender;
  }
}

export const OFFLINE_TTS_PINNED_ASSETS: OfflineTtsPinnedAsset[] = [
'''
    for item in assets:
        args = [item['path'], item['bytes'], item['sha256']]
        output += '  new OfflineTtsPinnedAsset(' + ', '.join(json.dumps(v) for v in args) + '),\n'
    output += '];\n\nexport const OFFLINE_TTS_PINNED_SPEAKERS: OfflineTtsPinnedSpeaker[] = [\n'
    for item in speakers:
        args = [item['id'], item['name'], item['language'], item['gender']]
        output += '  new OfflineTtsPinnedSpeaker(' + ', '.join(json.dumps(v) for v in args) + '),\n'
    return output + '];\n'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail when generated ArkTS does not match the pinned manifest')
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not OUTPUT_PATH.exists() or OUTPUT_PATH.read_text(encoding='utf-8') != output:
            raise SystemExit('OfflineTtsAssets.ets is stale; regenerate it')
        print('Pinned offline TTS assets and speaker mapping are current')
    else:
        OUTPUT_PATH.write_text(output, encoding='utf-8')
        print(f'Generated {OUTPUT_PATH}')


if __name__ == '__main__':
    main()

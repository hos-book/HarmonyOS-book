"""Generate the pinned, typed on-device model download manifest."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
manifest = json.loads((root / 'scripts/comic-offline-assets.json').read_text(encoding='utf-8'))
output = '''// Generated by scripts/generate-comic-model-assets.py; do not edit checksums manually.
export class ComicModelAsset {
  model: string;
  revision: string;
  path: string;
  size: number;
  sha256: string;
  constructor(model: string, revision: string, path: string, size: number, sha256: string) {
    this.model = model; this.revision = revision; this.path = path; this.size = size; this.sha256 = sha256;
  }
}

export const COMIC_MODEL_ASSETS: ComicModelAsset[] = [
'''
for model in manifest['models']:
    for item in model['files']:
        args = [model['id'], model['revision'], item['path'], item['size'], item['sha256']]
        output += '  new ComicModelAsset(' + ', '.join(json.dumps(v) for v in args) + '),\n'
output += '];\n'
(root / 'entry/src/main/ets/model/ComicModelAssets.ets').write_text(output, encoding='utf-8')

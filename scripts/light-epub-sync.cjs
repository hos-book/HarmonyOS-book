// Invoked through sync-light-source.cjs --epub [commit] [--check].
// Keep the upstream viewport and typography together; host patches only bind existing reader commands.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const project = path.resolve(__dirname, '..');
const manifestPath = path.join(project, 'third_party/light-source/epub-upstream.json');
const upstreamPath = 'entry/src/main/ets/core/book/EpubOriginalScript.ts';
const targetPath = 'entry/src/main/ets/service/text/light/EpubOriginalScript.ets';
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
function once(text, anchor, value) {
  if (text.split(anchor).length !== 2) throw Error(`EPUB upstream anchor changed: ${anchor}`);
  return text.replace(anchor, () => value);
}
function adapt(source, commit) {
  let text = once(source, "from './EpubOriginalDocument'", "from '../EpubOriginalDocument'");
  // The app owns paged gestures, including cancellation and simulation; the upstream owns layout/scrolling.
  for (const event of ['touchstart', 'touchend']) {
    const anchor = `document.addEventListener('${event}', function (e) {`;
    text = once(text, anchor, anchor + '\n    if (window.hsdaEpubConfig && window.hsdaEpubConfig.paged) return;');
  }
  text = once(text, "document.addEventListener('touchmove', function (e) {",
    "document.addEventListener('touchmove', function (e) {\n" +
    '    if (window.hsdaEpubConfig && window.hsdaEpubConfig.paged) { if (e.cancelable) e.preventDefault(); return; }');
  text = once(text, "document.addEventListener('click', function (e) {",
    "document.addEventListener('click', function (e) {\n" +
    '    if (window.hsdaEpubConfig && window.hsdaEpubConfig.paged) { e.preventDefault(); return; }');
  text = once(text, "window.addEventListener('resize', function () {\n    if (!started) return;\n    var s = spot();",
    "window.addEventListener('resize', function () {\n    if (!started) return;\n" +
    '    var s = window.hsdaEpub ? window.hsdaEpub.reflowSpot() : spot();');
  text = once(text, '    preview: preview };', `    preview: preview, state: function () {
      var s = spot();
      s.count = paged ? count : screenCount();
      s.page = paged ? page : Math.min(s.count - 1, Math.round(window.scrollY / screenStep()));
      return s;
    } };`);
  return `// Generated from wip3l/qingye-reader ${commit}; GPL-3.0.\n` +
    '// Update with scripts/sync-light-source.cjs --epub; do not edit this file.\n' + text;
}
async function sync(args) {
  const old = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : null;
  const revision = args.find(arg => /^[a-f0-9]{40}$/.test(arg)) || old?.commit;
  if (!revision) throw Error('Supply a full qingye-reader commit for the initial EPUB sync');
  const target = path.join(project, targetPath);
  if (old && fs.existsSync(target) && hash(fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n')) !== old.sha256) {
    throw Error('Local EPUB core change: update the host patch before syncing');
  }
  const url = `https://raw.githubusercontent.com/wip3l/qingye-reader/${revision}/${upstreamPath}`;
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw Error(`EPUB upstream: HTTP ${response.status}`);
  const source = (await response.text()).replaceAll('\r\n', '\n');
  const generated = adapt(source, revision);
  const manifest = { schemaVersion: 1, repository: 'https://github.com/wip3l/qingye-reader',
    commit: revision, upstreamPath, path: targetPath, license: 'GPL-3.0',
    patches: ['host-native-turn-and-position-v1'], upstreamSha256: hash(source), sha256: hash(generated) };
  if (args.includes('--check')) {
    if (!old || JSON.stringify(old) !== JSON.stringify(manifest) || !fs.existsSync(target) ||
      fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== generated) throw Error('EPUB upstream sync is stale');
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, generated);
    fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
  }
  console.log(`EPUB viewport ${args.includes('--check') ? 'verified' : 'synced'}: ${revision}`);
}
module.exports = { sync, adapt };

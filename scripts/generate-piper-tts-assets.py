"""Generate typed Piper allowlists and optionally verify the official archives."""
import argparse
import hashlib
import json
import re
import tarfile
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parent.parent
SPEC_PATH = ROOT / 'scripts/piper-tts-assets.json'
OUTPUT_PATH = ROOT / 'entry/src/main/ets/model/OfflineTtsPiperAssets.ets'
MODELS = {
    'piper-chaowen-int8-v1': (
        'vits-piper-zh_CN-chaowen-medium-int8',
        'zh_CN-chaowen-medium.onnx',
        'OFFLINE_TTS_PIPER_CHAOWEN_ASSETS',
        20933252,
    ),
    'piper-xiaoya-int8-v1': (
        'vits-piper-zh_CN-xiao_ya-medium-int8',
        'zh_CN-xiao_ya-medium.onnx',
        'OFFLINE_TTS_PIPER_XIAOYA_ASSETS',
        20933412,
    ),
}


def valid_path(value: str) -> bool:
    return (bool(value) and len(value) <= 256 and '\\' not in value
            and ':' not in value and not PurePosixPath(value).is_absolute()
            and all(part not in ('', '.', '..') for part in value.split('/'))
            and all(32 <= ord(character) <= 126 for character in value))


def read_spec() -> dict:
    spec = json.loads(SPEC_PATH.read_text(encoding='utf-8'))
    if spec.get('schemaVersion') != 1:
        raise ValueError('Unsupported Piper asset schema')
    models = spec['models']
    if [model['appModelId'] for model in models] != list(MODELS):
        raise ValueError('Expected the pinned Chaowen and Xiaoya model order')
    for model in models:
        model_id = model['appModelId']
        archive_root, onnx_name, _, total_bytes = MODELS[model_id]
        if (model['modelId'] != model_id or model['archiveRoot'] != archive_root
                or model['sampleRate'] != 22050
                or model['engine'] != 'sherpa-onnx-vits'
                or model['totalBytes'] != total_bytes
                or model['archive']['name'] != archive_root + '.tar.bz2'
                or re.fullmatch(r'[0-9a-f]{64}', model['archive']['sha256']) is None
                or model['archive']['bytes'] <= 0):
            raise ValueError(f'Invalid pinned Piper identity: {model_id}')
        if (len(model['speakers']) != 1 or model['speakers'][0]['id'] != 0
                or model['speakers'][0]['language'] != 'zh-CN'):
            raise ValueError('Each Piper checkpoint has one Chinese speaker, sid=0')
        files = model['files']
        required = {'MODEL_CARD', 'date.fst', 'lexicon.txt', 'number.fst',
                    'phone.fst', 'tokens.txt', onnx_name, onnx_name + '.json'}
        seen = set()
        for item in files:
            name, size = item['path'], item['bytes']
            if (not valid_path(name) or name in seen
                    or not isinstance(size, int) or isinstance(size, bool)
                    or not 0 < size <= 128 * 1024 * 1024
                    or re.fullmatch(r'[0-9a-f]{64}', item['sha256']) is None):
                raise ValueError(f'Invalid pinned Piper asset: {name}')
            seen.add(name)
        if (seen != required or len(files) != len(required)
                or sum(item['bytes'] for item in files) != total_bytes):
            raise ValueError(f'Unexpected pinned Piper asset budget: {model_id}')
    return spec


def generate(spec: dict) -> str:
    output = (
        '// Generated by scripts/generate-piper-tts-assets.py; do not edit checksums manually.\n'
        '// Official archive digests and provenance: scripts/piper-tts-assets.json.\n'
        "import { OfflineTtsPinnedAsset } from './OfflineTtsAssets';\n"
    )
    for model in spec['models']:
        export_name = MODELS[model['appModelId']][2]
        output += f'\nexport const {export_name}: OfflineTtsPinnedAsset[] = [\n'
        for item in model['files']:
            arguments = [item['path'], item['bytes'], item['sha256']]
            output += '  new OfflineTtsPinnedAsset(' + ', '.join(
                json.dumps(value) for value in arguments) + '),\n'
        output += '];\n'
    return output


def verify_archives(spec: dict, directory: Path) -> None:
    for model in spec['models']:
        archive = model['archive']
        archive_path = directory / archive['name']
        if archive_path.stat().st_size != archive['bytes']:
            raise ValueError(f'Archive size mismatch: {archive_path.name}')
        with archive_path.open('rb') as stream:
            if hashlib.file_digest(stream, 'sha256').hexdigest() != archive['sha256']:
                raise ValueError(f'Archive digest mismatch: {archive_path.name}')
        expected = {item['path']: item for item in model['files']}
        seen = set()
        with tarfile.open(archive_path, 'r:bz2') as source:
            for member in source:
                full_name = member.name.rstrip('/') if member.isdir() else member.name
                if not valid_path(full_name):
                    raise ValueError(f'Unsafe archive member: {member.name}')
                parts = full_name.split('/')
                if parts[0] != model['archiveRoot']:
                    raise ValueError(f'Unexpected archive root: {member.name}')
                if member.isdir():
                    continue
                relative_name = '/'.join(parts[1:])
                if (not member.isfile() or relative_name not in expected
                        or relative_name in seen):
                    raise ValueError(f'Unexpected archive member: {member.name}')
                item = expected[relative_name]
                if member.size != item['bytes']:
                    raise ValueError(f'Asset size mismatch: {member.name}')
                stream = source.extractfile(member)
                if stream is None:
                    raise ValueError(f'Missing archive member data: {member.name}')
                with stream:
                    actual_digest = hashlib.file_digest(stream, 'sha256').hexdigest()
                if actual_digest != item['sha256']:
                    raise ValueError(f'Asset digest mismatch: {member.name}')
                seen.add(relative_name)
        if seen != set(expected):
            raise ValueError(f'Missing assets in {archive_path.name}')
        print(f'Verified original archive and {len(seen)} pinned files: {archive_path.name}')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='Fail if the generated ArkTS file is stale')
    parser.add_argument('--verify-archives', type=Path,
                        help='Directory containing both original official tar.bz2 archives')
    args = parser.parse_args()
    spec = read_spec()
    if args.verify_archives:
        verify_archives(spec, args.verify_archives)
    output = generate(spec)
    if args.check:
        if not OUTPUT_PATH.exists() or OUTPUT_PATH.read_text(encoding='utf-8') != output:
            raise SystemExit('OfflineTtsPiperAssets.ets is stale; regenerate it')
        print('Pinned Piper assets are current')
    else:
        OUTPUT_PATH.write_text(output, encoding='utf-8', newline='\n')
        print(f'Generated {OUTPUT_PATH}')


if __name__ == '__main__':
    main()
